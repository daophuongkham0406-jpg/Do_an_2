-- PostgreSQL schema for AI Fitness Dataset
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS exercises (
    "exercise_id" TEXT PRIMARY KEY,
    "exercise_name" TEXT,
    "aliases" JSONB,
    "category" TEXT,
    "body_region" TEXT,
    "mechanics_type" TEXT,
    "movement_pattern" TEXT,
    "force_type" TEXT,
    "kinetic_chain" TEXT,
    "laterality" TEXT,
    "equipment" JSONB,
    "load_position" TEXT,
    "primary_muscles" JSONB,
    "secondary_muscles" JSONB,
    "stabilizer_muscles" JSONB,
    "movement_planes" JSONB,
    "joint_actions" JSONB,
    "range_of_motion_type" TEXT,
    "resistance_profile" TEXT,
    "muscle_length_bias" TEXT,
    "axial_loading" TEXT,
    "minimum_training_level" TEXT,
    "technical_complexity_score" REAL,
    "coordination_requirement" REAL,
    "stability_requirement" REAL,
    "mobility_requirement" REAL,
    "balance_requirement" REAL,
    "systemic_fatigue_score" REAL,
    "local_fatigue_score" REAL,
    "recommended_goals" JSONB,
    "relative_injury_risk" TEXT,
    "joint_stress_areas" JSONB,
    "contraindications" JSONB,
    "exercise_setup" TEXT,
    "execution_steps" JSONB,
    "common_mistakes" JSONB,
    "cues" JSONB,
    "breathing_pattern" TEXT,
    "progressions" JSONB,
    "regressions" JSONB,
    "alternatives" JSONB,
    "met_value" REAL,
    "source_ids" TEXT,
    "record_status" TEXT,
    "last_reviewed_date" TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
    "user_id" TEXT PRIMARY KEY,
    "username" TEXT,
    "gender" TEXT,
    "age" INTEGER,
    "height_cm" REAL,
    "weight_kg" REAL,
    "body_fat_percent" REAL,
    "bmi" REAL,
    "primary_goal" TEXT,
    "goal_filter_tags" JSONB,
    "secondary_goal" TEXT,
    "training_level" TEXT,
    "training_experience_months" INTEGER,
    "training_days_per_week" INTEGER,
    "session_duration_minutes" INTEGER,
    "available_training_days" TEXT,
    "available_equipment" JSONB,
    "priority_muscles" JSONB,
    "avoided_muscles" JSONB,
    "preferred_exercise_types" JSONB,
    "avoided_exercise_ids" JSONB,
    "injuries_or_limitations" JSONB,
    "medical_clearance_required" BOOLEAN,
    "preferred_split" TEXT,
    "activity_level" TEXT,
    "sleep_hours" REAL,
    "motivation_level" TEXT,
    "gym_access_level" TEXT,
    "progression_strategy" TEXT,
    "profile_status" TEXT,
    "created_at" TIMESTAMP,
    "updated_at" TIMESTAMP
);

CREATE TABLE IF NOT EXISTS workout_plans (
    "plan_id" TEXT PRIMARY KEY,
    "user_id" TEXT,
    "username_snapshot" TEXT,
    "primary_goal_snapshot" TEXT,
    "secondary_goal_snapshot" TEXT,
    "training_level_snapshot" TEXT,
    "plan_name" TEXT,
    "plan_type" TEXT,
    "plan_start_date" TIMESTAMP,
    "plan_end_date" TIMESTAMP,
    "duration_weeks" INTEGER,
    "days_per_week" INTEGER,
    "split_type" TEXT,
    "session_duration_target_min" REAL,
    "progression_strategy" TEXT,
    "weekly_set_target" INTEGER,
    "session_volume_target" INTEGER,
    "deload_strategy" TEXT,
    "plan_status" TEXT,
    "generation_source" TEXT,
    "generator_version" TEXT,
    "plan_version" TEXT,
    "exercise_item_count" INTEGER,
    "rationale" TEXT,
    "safety_notes" TEXT,
    "created_at" TIMESTAMP,
    "updated_at" TIMESTAMP,
    FOREIGN KEY ("user_id") REFERENCES users("user_id")
);

CREATE TABLE IF NOT EXISTS workout_plan_items (
    "plan_item_id" TEXT PRIMARY KEY,
    "plan_id" TEXT,
    "week_number" INTEGER,
    "day_number" INTEGER,
    "day_name" TEXT,
    "day_type" TEXT,
    "session_name" TEXT,
    "exercise_role" TEXT,
    "priority_score" REAL,
    "selection_reason" TEXT,
    "focus_muscles" JSONB,
    "exercise_order" INTEGER,
    "exercise_id" TEXT,
    "exercise_name_snapshot" TEXT,
    "exercise_min_level_snapshot" TEXT,
    "exercise_goals_snapshot" JSONB,
    "exercise_equipment_snapshot" JSONB,
    "primary_muscles_snapshot" JSONB,
    "sets" INTEGER,
    "rep_min" INTEGER,
    "rep_max" INTEGER,
    "duration_seconds" INTEGER,
    "intensity_unit" TEXT,
    "target_intensity" REAL,
    "rest_seconds" INTEGER,
    "tempo" TEXT,
    "set_type" TEXT,
    "warmup_sets" INTEGER,
    "is_optional" BOOLEAN,
    "progression_rule" TEXT,
    "substitution_exercise_ids" JSONB,
    "coaching_note" TEXT,
    FOREIGN KEY ("plan_id") REFERENCES workout_plans("plan_id"),
    FOREIGN KEY ("exercise_id") REFERENCES exercises("exercise_id")
);

CREATE TABLE IF NOT EXISTS workout_history_sessions (
    "history_session_id" TEXT PRIMARY KEY,
    "user_id" TEXT,
    "plan_id" TEXT,
    "week_number" INTEGER,
    "day_number" INTEGER,
    "planned_day_name" TEXT,
    "planned_session_name" TEXT,
    "scheduled_date" TIMESTAMP,
    "completion_status" TEXT,
    "planned_item_count" INTEGER,
    "completed_item_count" INTEGER,
    "completion_pct" REAL,
    "planned_working_sets" INTEGER,
    "completed_working_sets" INTEGER,
    "set_completion_pct" REAL,
    "session_duration_target_min" REAL,
    "actual_duration_min" INTEGER,
    "session_rpe" REAL,
    "energy_before" INTEGER,
    "fatigue_after" INTEGER,
    "sleep_hours_snapshot" REAL,
    "body_weight_kg_snapshot" REAL,
    "pain_reported" TEXT,
    "pain_areas" JSONB,
    "readiness_score" REAL,
    "recovery_flag" TEXT,
    "record_source" TEXT,
    "is_synthetic" BOOLEAN,
    "notes" TEXT,
    "created_at" TIMESTAMP,
    FOREIGN KEY ("user_id") REFERENCES users("user_id"),
    FOREIGN KEY ("plan_id") REFERENCES workout_plans("plan_id")
);

CREATE TABLE IF NOT EXISTS workout_history_items (
    "history_item_id" TEXT PRIMARY KEY,
    "history_session_id" TEXT,
    "user_id" TEXT,
    "plan_id" TEXT,
    "plan_item_id" TEXT,
    "exercise_id" TEXT,
    "exercise_name_snapshot" TEXT,
    "exercise_order" INTEGER,
    "planned_sets" INTEGER,
    "planned_rep_min" INTEGER,
    "planned_rep_max" INTEGER,
    "planned_target_rpe" REAL,
    "planned_rest_seconds" INTEGER,
    "actual_sets_completed" INTEGER,
    "actual_reps_json" JSONB,
    "actual_load_kg" REAL,
    "actual_rpe" REAL,
    "completion_status" TEXT,
    "pain_during_exercise" TEXT,
    "pain_areas" JSONB,
    "technique_quality" TEXT,
    "difficulty_rating" INTEGER,
    "exercise_enjoyment" INTEGER,
    "feedback_signal" TEXT,
    "record_source" TEXT,
    "is_synthetic" BOOLEAN,
    "notes" TEXT,
    "created_at" TIMESTAMP,
    FOREIGN KEY ("history_session_id") REFERENCES workout_history_sessions("history_session_id"),
    FOREIGN KEY ("user_id") REFERENCES users("user_id"),
    FOREIGN KEY ("plan_id") REFERENCES workout_plans("plan_id"),
    FOREIGN KEY ("plan_item_id") REFERENCES workout_plan_items("plan_item_id"),
    FOREIGN KEY ("exercise_id") REFERENCES exercises("exercise_id")
);

CREATE TABLE IF NOT EXISTS workout_history_summary (
    "summary_id" TEXT PRIMARY KEY,
    "user_id" TEXT,
    "plan_id" TEXT,
    "representative_week" INTEGER,
    "representative_day" INTEGER,
    "session_status" TEXT,
    "session_completion_pct" REAL,
    "set_completion_pct" REAL,
    "session_rpe" REAL,
    "fatigue_after" INTEGER,
    "pain_reported" TEXT,
    "avg_difficulty" REAL,
    "avg_enjoyment" REAL,
    "positive_items" INTEGER,
    "neutral_items" INTEGER,
    "negative_items" INTEGER,
    "recovery_flag" TEXT,
    "progression_recommendation" TEXT,
    FOREIGN KEY ("user_id") REFERENCES users("user_id"),
    FOREIGN KEY ("plan_id") REFERENCES workout_plans("plan_id")
);

CREATE TABLE IF NOT EXISTS user_feedback (
    "feedback_id" TEXT PRIMARY KEY,
    "user_id" TEXT,
    "plan_id" TEXT,
    "history_session_id" TEXT,
    "history_item_id" TEXT,
    "plan_item_id" TEXT,
    "exercise_id" TEXT,
    "feedback_scope" TEXT,
    "feedback_type" TEXT,
    "rating" INTEGER,
    "sentiment" TEXT,
    "difficulty_feedback" TEXT,
    "enjoyment_rating" INTEGER,
    "fatigue_feedback" TEXT,
    "pain_feedback" TEXT,
    "pain_areas" JSONB,
    "duration_feedback" TEXT,
    "exercise_preference" TEXT,
    "progression_preference" TEXT,
    "requested_action" TEXT,
    "feedback_text" TEXT,
    "feedback_reason_tags" JSONB,
    "source_context" TEXT,
    "feedback_status" TEXT,
    "record_source" TEXT,
    "is_synthetic" BOOLEAN,
    "created_at" TIMESTAMP,
    "updated_at" TIMESTAMP,
    FOREIGN KEY ("user_id") REFERENCES users("user_id"),
    FOREIGN KEY ("plan_id") REFERENCES workout_plans("plan_id"),
    FOREIGN KEY ("history_session_id") REFERENCES workout_history_sessions("history_session_id"),
    FOREIGN KEY ("history_item_id") REFERENCES workout_history_items("history_item_id"),
    FOREIGN KEY ("plan_item_id") REFERENCES workout_plan_items("plan_item_id"),
    FOREIGN KEY ("exercise_id") REFERENCES exercises("exercise_id")
);
